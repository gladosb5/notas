// Generate before packaging; --check fails closed in npm test when any shipped
// recognition code, weights, vocabulary or runtime has changed since stamping.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
// The visible app version and its offline worker must identify the same
// release, including when a deployment stamps the contract automatically.
const release=/const CACHE='notas-local-(v\d+)'/.exec(readFileSync('sw.js','utf8'))?.[1];
const page=readFileSync('notas.html','utf8');
if(!release||!/<meta name="notas-version" content="v\d+">/.test(page))throw Error('App release metadata is missing.');
const stamped=page.replace(/<meta name="notas-version" content="v\d+">/,'<meta name="notas-version" content="'+release+'">');
if(stamped!==page){
  if(process.argv.includes('--check'))throw Error('App release metadata is stale. Run node scripts/model-contract.mjs.');
  writeFileSync('notas.html',stamped);
}
// Recognition compatibility is independent of HTML, CSS and release stamps.
const common=['local-recognition.js'];
// the ONNX runtime shared by the workers still lives in assets/smart/
const runtime=['assets/smart/ort.wasm.min.js','assets/smart/ort-wasm-simd-threaded.js','assets/smart/ort-wasm-simd-threaded.wasm'];
const swPath='sw.js',sw=readFileSync(swPath,'utf8');
// Each split background runtime file is content-addressed by its own bytes,
// while the manifest also verifies the assembled binary.
const bgRuntime=JSON.parse(/self\.NOTAS_BG_RUNTIME=(\{[^\n]+\});?/.exec(readFileSync('assets/bg/model.js','utf8'))[1]);
const joined=createHash('sha256');let runtimeBytes=0;
for(const part of bgRuntime.parts){
  if(!/^[\w.-]+\.bin$/.test(part.file))throw Error('Invalid background runtime chunk path.');
  const bytes=readFileSync('assets/smart/'+part.file);
  if(bytes.length!==part.bytes||createHash('sha256').update(bytes).digest('hex')!==part.sha256)throw Error('Damaged background runtime chunk: '+part.file);
  joined.update(bytes);runtimeBytes+=bytes.length;
}
if(runtimeBytes!==bgRuntime.bytes||joined.digest('hex')!==bgRuntime.sha256)throw Error('Incomplete background runtime.');
const offlineFiles=[...runtime,'assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt',
  'assets/smart/ort.webgpu.min.js','assets/smart/ort-wasm-simd-threaded.asyncify.js',
  ...bgRuntime.parts.map(part=>'assets/smart/'+part.file)];
const offlineHashes=Object.fromEntries(offlineFiles.map(file=>[file,createHash('sha256').update(readFileSync(file)).digest('hex')]));
const verifiedSW=sw.replace(/const ASSET_HASHES=.*?;/,'const ASSET_HASHES='+JSON.stringify(offlineHashes)+';');
if(verifiedSW!==sw){if(process.argv.includes('--check'))throw Error('Offline integrity hashes are stale. Run scripts/model-contract.mjs.');writeFileSync(swPath,verifiedSW);}
const textRecognition=['text-worker.js','assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt'];
const inkRecognition=['ink-worker.js','ink-features.js','assets/ink/encoder.onnx','assets/ink/decoder_step.onnx','assets/ink/vocab.json'];
// Math now uses independent text evidence for named quantities. A text-model
// update must invalidate cached math readings as well as search transcripts.
const sets={math:[...common,...inkRecognition,...textRecognition,...runtime],text:[...common,...textRecognition,...runtime]};
const contract={};
// A newly stamped result version must not legitimize an old asset URL. Require
// each production worker to request the actual content hash it is stamped with.
for(const [worker,files] of Object.entries({
  'ink-worker.js':['assets/ink/encoder.onnx','assets/ink/decoder_step.onnx','assets/ink/vocab.json',...runtime],
  'text-worker.js':['assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt',...runtime],
  // the service worker precaches the same URLs, so it must name the same hashes
  'sw.js':['assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt',...runtime]
})){
  const source=readFileSync(worker,'utf8');
  for(const file of files){
    const hash=createHash('sha256').update(readFileSync(file)).digest('hex').slice(0,8);
    if(!source.includes(file.split('/').at(-1)+'?v='+hash))throw Error(`${worker} has a stale content URL for ${file}; expected v=${hash}`);
  }
}
for(const [kind,files] of Object.entries(sets)){
  const hashes=Object.fromEntries(files.map(file=>[file,createHash('sha256').update(readFileSync(file)).digest('hex')]));
  contract[kind]={id:createHash('sha256').update(JSON.stringify(hashes)).digest('hex').slice(0,16),hashes};
}
const content='// Generated by scripts/model-contract.mjs. Do not edit.\nglobalThis.NOTAS_MODEL_CONTRACT='+JSON.stringify(contract,null,2)+';\n';
if(process.argv.includes('--check')){
  if(readFileSync('model-contract.js','utf8')!==content)throw Error('Recognition contract is stale. Run node scripts/model-contract.mjs before packaging and rerun benchmarks.');
}else writeFileSync('model-contract.js',content);

