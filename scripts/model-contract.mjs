// Generate before packaging; --check fails closed in npm test when any shipped
// recognition code, weights, vocabulary or runtime has changed since stamping.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const common=['local-recognition.js','notas.html'];
// the ONNX runtime shared by the workers still lives in assets/smart/
const runtime=['assets/smart/ort.wasm.min.js','assets/smart/ort-wasm-simd-threaded.js','assets/smart/ort-wasm-simd-threaded.wasm'];
const textRecognition=['text-worker.js','assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt'];
const inkRecognition=['ink-worker.js','ink-features.js','assets/ink/encoder.onnx','assets/ink/decoder_step.onnx','assets/ink/vocab.json'];
// Math now uses independent text evidence for named quantities. A text-model
// update must invalidate cached math readings as well as search transcripts.
const sets={math:[...common,...inkRecognition,...textRecognition,...runtime],text:[...common,...textRecognition,...runtime]};
const contract={};
// A newly stamped result version must not legitimize an old asset URL. Require
// each production worker to request the actual content hash it is stamped with.
for(const [worker,files] of Object.entries({
  'ink-worker.js':['assets/ink/encoder.onnx','assets/ink/decoder_step.onnx','assets/ink/vocab.json',...runtime],
  'text-worker.js':['assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt',...runtime],
  // the service worker precaches the same URLs, so it must name the same hashes
  'sw.js':['assets/text/ppocrv6-small.onnx','assets/text/ppocrv6_dict.txt',...runtime]
})){
  const source=readFileSync(worker,'utf8');
  for(const file of files){
    const hash=createHash('sha256').update(readFileSync(file)).digest('hex').slice(0,8);
    if(!source.includes(file.split('/').at(-1)+'?v='+hash))throw Error(`${worker} has a stale content URL for ${file}; expected v=${hash}`);
  }
}
for(const [kind,files] of Object.entries(sets)){
  const hashes=Object.fromEntries(files.map(file=>[file,createHash('sha256').update(readFileSync(file)).digest('hex')]));
  contract[kind]={id:createHash('sha256').update(JSON.stringify(hashes)).digest('hex').slice(0,16),hashes};
}
const content='// Generated by scripts/model-contract.mjs. Do not edit.\nglobalThis.NOTAS_MODEL_CONTRACT='+JSON.stringify(contract,null,2)+';\n';
if(process.argv.includes('--check')){
  if(readFileSync('model-contract.js','utf8')!==content)throw Error('Recognition contract is stale. Run node scripts/model-contract.mjs before packaging and rerun benchmarks.');
}else writeFileSync('model-contract.js',content);

